"""Regenerate the four local step proofs using only the Python standard library.

The JSON describes candidate affine predicates. Lean proves their base, transition,
and periodicity properties; neither this generator nor its discovery process is trusted.
Use --check to compare artifacts without changing files.
"""
import json,re,sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
P=HERE/"templates"
CHECK="--check" in sys.argv
D=json.loads((HERE/'model.json').read_text());nodes=D['nodes'];roots=D['roots']
forms={2:'X',4:'T-N',5:'X-T',6:'X+T-2*N',7:'2*X-T-N',8:'2*X-T+3*N',9:'T-3*N',10:'X-N'}
def call(i):return 'False' if i==0 else 'True' if i==1 else f'p{i} N T X'
compact=''
for i in range(2,len(nodes)):
 f,k,a,b=nodes[i]
 compact+=f'@[simp] def p{i} (N T X : ℤ) : Prop := if {forms[f]} ≤ {k} then {call(a)} else {call(b)}\n'
for r in range(24):
 compact+=f'\ndef b{r} (s v : ℕ) (N T X : ℤ) : Prop :=\n'
 for t in range(12):
  compact+=f'  if s={t} then\n'
  for v in range(12):compact+=f'    if v={v} then {call(roots[(r*12+t)*12+v])} else\n'
  compact+='    False else\n'
 compact+='  False\n'
compact+='\ndef cell (n t x : ℤ) : Prop :=\n  reduced (n%24).toNat (t%12).toNat (x%12).toNat (n/24) (t/12) (x/12)\nend Compact\n'
inner_template=(P/'inner.lean.txt').read_text()
edge_template=(P/'edges.lean.txt').read_text()
edges=''
for r in range(24):
 q,v=divmod(r-1,12);q2,v2=divmod(r-2,12)
 edges+=edge_template.format(r=r,q=q,v=v,q2=q2,v2=v2)
edges+='end Compact\n' 
def decl(text,name,kind='lemma'):
 m=re.search(rf'^{kind} {name}\b.*?(?=^(?:lemma|theorem|def|end)\b|\Z)',text,re.S|re.M)
 if not m:raise ValueError(name)
 return m[0].rstrip()+'\n\n'
def clean(text):
 return '\n'.join(l for l in text.splitlines() if not l.startswith(('import ','set_option ')))+'\n'
def scoped(text):
 return re.sub(r'^(lemma|theorem) ', 'set_option maxRecDepth 10000 in\nset_option maxHeartbeats 10000000 in\n\\1 ',text,flags=re.M)
for g in range(4):
 rs=list(range(g,24,4));used=set()
 def visit(i):
  if i in used:return
  used.add(i)
  if i>1:visit(nodes[i][2]);visit(nodes[i][3])
 for r in rs:
  for i in roots[r*144:(r+1)*144]:visit(i)
 s=f'''import OMAReductions.R_oeis_a334502_R1

/-!
# A334502, step H{g+1}: widths congruent to {g} modulo four
Credit: @ddanila

The proof uses a finite collection of affine cell predicates, selected by the
width, time and position residues. These describe a candidate orbit, not an
assumption about the cellular automaton. Lean checks the seed and every local
update, including wraparound, for arbitrary integer quotients. Cellwise induction
then identifies the actual rows. At time 12*n the model returns after three steps
and its cell at position two changes after one step.

The arithmetic tables are generated by problems/a334502/generate.py. Their
correctness is checked here by ordinary simplification and omega; no external
solver or generated certificate is trusted.
-/
namespace Compact
'''
 for line in compact.splitlines():
  m=re.match(r'@\[simp\] def p(\d+) ',line)
  if m and int(m[1]) in used:
   body=line.split(':=',1)[1]
   for name in ['N','T','X']:
    if not re.search(r'\b'+name+r'\b',body):line=line.replace(' '+name+' ', ' _'+name+' ',1)
   s+=line+'\n'
 for r in rs:s+=decl(compact,f'b{r}','def')
 s+='def reduced (r s v : ℕ) (N T X : ℤ) : Prop :=\n'
 for r in rs:s+=f'  if r={r} then b{r} s v N T X else\n'
 s+='  False\n\n'
 s+=decl(compact,'cell','def')
 blocks=''.join(inner_template.format(r=r) for r in rs)+'end Compact\n'
 for r in rs:s+=decl(blocks,f'inner_{r}')
 for r in rs:
  for name in ['left','right','base','periodic','different']:s+=decl(edges,f'{name}_{r}')
 ar=clean((P/'CompactArithmetic.lean').read_text());s+=ar[ar.index('lemma residue_nat'):ar.rindex('end Compact')]
 alltext=(P/'CompactAll.lean').read_text()
 for name in ['inner','left','right','base','periodic','different']:
  d=decl(alltext,name+'_all')
  d=d.replace('(hr : r<24)',f'(hr : r<24) (hg : r%4={g})')
  for r in range(24):
   if r not in rs:d=re.sub(rf'^  · exact {name}_{r} .*$', '  · omega',d,flags=re.M)
  s+=d
 dyn=clean((P/'CompactDynamics.lean').read_text());dyn=dyn[dyn.index('lemma inner_step'):dyn.rindex('end Compact')]
 dyn=dyn.replace('(hn : 14≤n)',f'(hg : (n%24).toNat%4={g}) (hn : 14≤n)')
 dyn=dyn.replace('(residue_nat n 24 (by decide)) (by omega)', '(residue_nat n 24 (by decide)) hg (by omega)')
 s+=dyn+'\nend Compact\n\n'
 bridge=clean((P/'Bridge.lean').read_text());s+=bridge+'\n'
 finish=clean((P/'Finish.lean').read_text())
 finish=finish[:finish.index('/-- On a three-cycle')]
 pair=decl((P/'Finish.lean').read_text(),'certificate_of_model').replace('certificate_of_model','pair_of_model').replace('Certificate n T 3','row n (T+3)=row n T ∧ row n (T+1)≠row n T').replace('  apply certificate_three','  constructor')
 s+=finish+pair+'end A334502Local\n\n'
 final=clean((P/'CompactFinish.lean').read_text());final=final[final.index('namespace A334502Local'):final.index('\nnamespace OMA')]
 final=final.replace('(hn : 14≤n)',f'(hn : 14≤n) (hg : n%4={g})')
 final=final.replace('Compact.left_step n t (by omega)', 'Compact.left_step n t (by omega) (by omega)')
 final=final.replace('Compact.right_step n t (by omega)', 'Compact.right_step n t (by omega) (by omega)')
 final=final.replace('Compact.inner_step n t i (by omega)', 'Compact.inner_step n t i (by omega) (by omega)')
 final=final.replace('theorem largeCycles : LargeCycles := by\n  intro n hn',f'theorem result : OMA.R_oeis_a334502_R1.H{g+1} := by\n  intro n hn hg')
 final=final.replace('Compact.initial n i (by omega)', 'Compact.initial n i (by omega) (by omega)')
 final=final.replace('(cell_step_nat n · · hn)', '(fun t i hi => cell_step_nat n t i hn hg hi)')
 final=final.replace('certificate_of_model','pair_of_model')
 final=final.replace('Compact.period n i (by omega)', 'Compact.period n i (by omega) (by omega)')
 final=final.replace('Compact.nonfixed n (by omega)', 'Compact.nonfixed n (by omega) (by omega)')
 s+=final+f'\ntheorem OMA.solution : OMA.R_oeis_a334502_R1.H{g+1} := A334502Local.result\n'
 s=scoped(s)
 s=re.sub(r'(/--(?:(?!-/).)*-/\n)(set_option[^\n]*\nset_option[^\n]*\n)',r'\2\1',s,flags=re.S)
 for name in ['hn','ht','hs','hv','hx','hxn','hr','hg','hs\'','hv\'']:
  s=re.sub(r'\b'+re.escape(name)+r'\b','_'+name,s)
 # Avoid warnings from deliberately uniform table parameters without disabling lint.
 for i in used:
  if i<2:continue
  # All parameters remain explicit; omega uses most hypothesis names implicitly.
 target=ROOT/f'proofs/oeis-a334502.R1.H{g+1}.lean'
 if CHECK:
  if target.read_text()!=s:raise SystemExit(f'Generated artifact differs: {target}')
 else:target.write_text(s)
 print(f'{target.name}: {len(s.encode())} bytes'+(' (matches)' if CHECK else ''),flush=True)
